// ABOUTME: withdrawal codec and the Hedera transaction body it signs.

import { bytesToHex } from "viem"
import { describe, expect, test } from "vitest"

import {
  DecodedHederaVmWithdrawal,
  decodeWithdrawal,
  encodeWithdrawal,
  getDecodedWithdrawalAmount,
  getDecodedWithdrawalCurrency,
  getDecodedWithdrawalId,
  getDecodedWithdrawalRecipient,
} from "../src/messages/v2.1/depository-withdrawal"
import { getHederaVmTransactionBody } from "../src/messages/v2.1/withdrawals/hedera-vm"
import { HEDERA_HBAR_TOKEN_ID, HEDERA_MAINNET_USDC_TOKEN_ID } from "../src"

type Withdrawal = DecodedHederaVmWithdrawal["withdrawal"]

const BASE: Withdrawal = {
  payer: "0.0.98",
  sender: "0.0.1001",
  receiver: "0.0.2002",
  amount: "500000000",
  token: HEDERA_HBAR_TOKEN_ID,
  nodeAccount: "0.0.3",
  validStart: "1700000000.123456789",
  validDurationSeconds: 120,
  maxTransactionFee: "100000000",
}

const withdrawal = (overrides: Partial<Withdrawal> = {}): Withdrawal => ({
  ...BASE,
  ...overrides,
})

const decoded = (
  overrides: Partial<Withdrawal> = {}
): DecodedHederaVmWithdrawal => ({
  vmType: "hedera-vm",
  withdrawal: withdrawal(overrides),
})

const body = (overrides: Partial<Withdrawal> = {}): string =>
  bytesToHex(getHederaVmTransactionBody(withdrawal(overrides)))

// Golden transaction bodies, generated by the Hedera JavaScript SDK v2.81.0
// (`TransferTransaction ... .freeze()`, taking `bodyBytes`) for the same
// transfers. HederaVmPayloadBuilder.sol pins the identical vectors, so all
// three implementations agree byte for byte.
